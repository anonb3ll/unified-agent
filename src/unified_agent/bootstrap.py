"""Cold-start bootstrap: ``unified-agent init`` and ``unified-agent doctor``.

These make a fresh machine self-serve. ``init`` creates UA_HOME, builds an
empty database, and drops a starter env file with a generated bearer token;
``doctor`` runs :func:`unified_agent.tools.doctor.system_doctor` from a shell
and exits non-zero on a real misconfiguration, so a cold install can be gated
in CI or a provisioning script.

Both are also wired into ``unified-agent`` as subcommands (see
``server.main``), matching the existing ``unified-agent audit`` pattern —
``unified-agent init`` / ``unified-agent doctor`` and the standalone
``unified-agent-init`` / ``unified-agent-doctor`` binaries are the same code.
"""

