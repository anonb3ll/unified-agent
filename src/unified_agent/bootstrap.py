# Deployment settings an existing service.env owns. ``init --force`` rotates
# bearers and re-asserts identity and workspace, but never resets these to the
# template's cold-start defaults (task #1774): a hub serving over http with auth
# enforced must not silently fall back to stdio and open auth. ``init`` has no
# flag for them, so an existing value is always kept.
_FORCE_PRESERVED_KEYS = frozenset(
    {"UA_TRANSPORT", "UA_ENFORCE_AUTH", "UA_APPROVAL_TOOLS", "UA_MCP_OAUTH"}
)

# The sandbox root is a security boundary, so after init it is pinned here and
# settings.toml cannot move it (#1806, #1825).
_WORKSPACE_PINNED = """\
# Sandbox root for fs_*/run_cmd. This line is authoritative: settings.toml
# paths.workspace is informational and cannot move it. Change it here or with
# `unified-agent init --workspace PATH`.
UA_WORKSPACE={workspace}"""

# The comment settings-enabled installs carried above a commented-out
# `# UA_WORKSPACE=` line before #1825. Re-init replaces the whole stanza.
_LEGACY_WORKSPACE_COMMENT = (
    "# Sandbox root for fs_*/run_cmd. It lives in settings.toml (paths.workspace);",
    "# edit it there. An uncommented line here would win over settings.toml.",
)
_COMMENTED_WORKSPACE = re.compile(r"\s*#\s*(?:export\s+)?UA_WORKSPACE\s*=")


def _workspace_block(workspace) -> str:
    """The service.env workspace stanza: always a live, authoritative pin."""
    return _WORKSPACE_PINNED.format(workspace=shlex.quote(str(workspace)))


def _resolve_workspace_pin(raw: str) -> str:
    """``service_env.resolve_workspace_pin`` as init's ``SettingsError``.

    The rule itself lives there so ``system_doctor`` judges a pin exactly as
    init does.
    """
    from . import settings

    try:
        return str(resolve_workspace_pin(raw))
    except ValueError as exc:
        raise settings.SettingsError(str(exc)) from exc


def _workspace_pin_update(prior: dict[str, str], workspace) -> str | None:
    """The ``UA_WORKSPACE`` value to write, or None when the pin already names it."""
    from . import settings

    raw = (prior.get("UA_WORKSPACE") or "").strip()
    if raw:
        try:
            if _resolve_workspace_pin(raw) == str(workspace):
                return None
        except settings.SettingsError:
            pass  # an explicit --workspace replaces an unresolvable pin
    return str(workspace)


def _pin_workspace_in_place(env_path, workspace: str) -> None:
    """Write an uncommented ``UA_WORKSPACE`` pin, keeping other lines as written.

    An existing assignment is replaced where it stands. Otherwise the last
    commented-out ``# UA_WORKSPACE=`` line (and the pre-#1825 comment above it)
    becomes the pinned stanza; with neither, the stanza is appended.
    """
    if "UA_WORKSPACE" in parse_env_file_raw(env_path):
        merge_write_env_file(env_path, {"UA_WORKSPACE": workspace}, preserve_lines=True)
        return
    lines = env_path.read_text(encoding="utf-8").splitlines(keepends=True)
    block = _workspace_block(workspace) + "\n"
    for index in range(len(lines) - 1, -1, -1):
        if _COMMENTED_WORKSPACE.match(lines[index]):
            start = index
            legacy = list(_LEGACY_WORKSPACE_COMMENT)
            while legacy and start > 0 and lines[start - 1].strip() == legacy[-1]:
                legacy.pop()
                start -= 1
            lines[start : index + 1] = [block]
            break
    else:
        if lines and not lines[-1].endswith("\n"):
            lines[-1] += "\n"
        lines.append(("\n" if lines else "") + block)
    write_env_text(env_path, "".join(lines))


def _prompt(question: str, default: str) -> str:
    try:
        answer = input(f"{question} [{default}]: ").strip()
    except EOFError:
        return default
    return answer or default


def _external_operator_value(key: str) -> str | None:
    """Distinguish real environment pins from values seeded by settings."""
    from . import settings

    value = os.environ.get(key)
    if value is None or settings.applied_from_file().get(key) == value:
        return None
    return value


def _installed_operator_value(prior: dict[str, str], key: str, env_path) -> str:
    """Read a literal pin or an already available simple shell variable.

    Never source an installation file or trust UA_OPERATOR_* seeded from TOML
    as proof that its shell expression was evaluated. Unsupported/unavailable
    expressions fail before provisioning and do not disclose their contents.
    """
    from . import settings

    value = prior.get(key, "")
    if "$" not in value and "`" not in value:
        return value
    # shlex parsing erases the difference between a literal '$VAR' and an
    # expanding "$VAR". Inspect the last assignment, matching runtime's
    # duplicate/export handling, and accept only a whole plain variable.
    expression = ""
    try:
        for line in env_path.read_text(encoding="utf-8").splitlines():
            raw = line.strip()
            if raw.startswith("export "):
                raw = raw[7:].lstrip()
            field, sep, rhs = raw.partition("=")
            if sep and field.strip() == key:
                expression = rhs.strip()
    except OSError as exc:
        raise settings.SettingsError(f"cannot read {key} from service.env") from exc
    if expression.startswith('"') and expression.endswith('"'):
        expression = expression[1:-1]
    match = re.fullmatch(r"\$(?:([A-Za-z_][A-Za-z0-9_]*)|\{([A-Za-z_][A-Za-z0-9_]*)\})", expression)
    if match:
        variable = match.group(1) or match.group(2)
        if (
            variable in os.environ
            and settings.applied_from_file().get(variable) != os.environ[variable]
        ):
            return os.environ[variable]
    flag = "--operator-name" if key == "UA_OPERATOR_NAME" else "--operator-label"
    remedy = (
        f"pass {flag} to replace this pin"
        if key != "UA_OPERATOR_ALIASES"
        else "use a literal alias list"
    )
    raise settings.SettingsError(
        f"cannot resolve {key} from service.env: export its referenced variable "
        f"or {remedy}; initialization does not execute shell expressions"
    )


def _personalization(args: argparse.Namespace, home) -> dict:
    """Settings.toml content for this install, from flags and/or prompts."""
    from . import settings

    existing = settings.load(settings.settings_path())
    op = dict(existing.get("operator") or {})
    paths = dict(existing.get("paths") or {})
    prior_env = parse_env_file(home / "service.env")
    # Preserve genuine external identity declarations when no installed file
    # pins that field. Ignore prior TOML seeds if this invocation's file differs.
    for field, key in (
        ("name", "UA_OPERATOR_NAME"),
        ("label", "UA_OPERATOR_LABEL"),
        ("aliases", "UA_OPERATOR_ALIASES"),
    ):
        external = _external_operator_value(key)
        if key not in prior_env and external is not None:
            op[field] = (
                [a.strip() for a in external.split(",") if a.strip()]
                if field == "aliases"
                else external
            )
    # service.env outranks TOML at runtime. Each omitted identity flag keeps
    # the effective installed value, even if TOML declares an older identity.
    for field, key in (("name", "UA_OPERATOR_NAME"), ("label", "UA_OPERATOR_LABEL")):
        if prior_env.get(key) and not getattr(args, f"operator_{field}"):
            op[field] = _installed_operator_value(prior_env, key, home / "service.env")
    if "UA_OPERATOR_ALIASES" in prior_env:
        op["aliases"] = [
            a.strip()
            for a in _installed_operator_value(
                prior_env, "UA_OPERATOR_ALIASES", home / "service.env"
            ).split(",")
            if a.strip()
        ]

    name = args.operator_name or op.get("name") or _name_from_aliases(op.get("aliases"))
    label = args.operator_label or op.get("label")
    # service.env owns the sandbox root once init has run (#1806): an explicit
    # flag moves it, else an installed pin keeps it, else settings.toml (first
    # pin of an older settings-enabled install) or the code default seeds it.
    prior_pin = (prior_env.get("UA_WORKSPACE") or "").strip()
    if args.workspace:
        workspace = args.workspace
    elif prior_pin:
        workspace = _resolve_workspace_pin(prior_pin)
    else:
        workspace = paths.get("workspace") or str(home / "workspace")
    vault = args.vault if args.vault is not None else paths.get("vault")
    if args.interactive:
        name = _prompt("Your name (shown on approvals and evidence)", name)
        label = _prompt(
            "Your login label (the identity your own token resolves to)",
            label or _operator_label_for(name),
        )
        workspace = _prompt("Agent workspace directory", workspace)
        # A blank answer accepts the bracketed default, so with a saved path
        # it keeps that path. "-" is the explicit way to disable the vault.
        vault_hint = "blank keeps the current path, '-' disables" if vault else "blank to disable"
        vault = _prompt(f"Obsidian-style vault path ({vault_hint})", vault or "")
        if vault == "-":
            vault = ""
    label = label or _operator_label_for(name)
    existing_env, _ = settings.to_env(existing)
    roster = (existing_env.get("UA_AGENT_LABELS") or "").split(":")
    roster += (parse_env_file(home / "service.env").get("UA_AGENT_LABELS") or "").split(":")
    if label.casefold() in {worker.strip().casefold() for worker in roster if worker.strip()}:
        raise SystemExit(f"operator label {label!r} names a configured worker")
    problem = config.operator_label_problem(label)
    if problem is not None:
        # Same rule the hub applies at runtime: refuse here rather than save a
        # label (and mint a token for it) that the hub would then ignore.
        raise SystemExit(
            f"operator label {label!r} {problem}: use a label that starts with a "
            "letter, uses only letters, digits, '_' or '-' (max 64), and is not an "
            "agent identity such as Desktop_Agent2 (pass --operator-label)"
        )
    op.update({"name": name, "label": label})
    paths["workspace"] = workspace
    if vault is not None:
        paths["vault"] = vault
    data = {k: v for k, v in existing.items() if k not in ("operator", "paths")}
    data["schema_version"] = settings.SCHEMA_VERSION
    data["operator"] = op
    data["paths"] = paths
    return data


def _name_from_aliases(aliases) -> str:
    """The operator name an alias-only install already runs under.

    Mirrors ``config.operator_name()``: with no explicit name, the first alias
    that does not name a catalogued or credential-backed worker is the
    effective name. Saving the generic default instead would pin it as an
    explicit name and silently drop the alias on the next process start.
    """
    for alias in aliases or ():
        alias = str(alias).strip()
        if alias and not config._names_worker_identity(alias, include_roster=False):
            return alias
    return config.DEFAULT_OPERATOR_NAME


def _operator_label_for(name: str) -> str:
    ascii_name = unicodedata.normalize("NFKD", name).encode("ascii", "ignore").decode("ascii")
    slug = "".join(ch if ch.isalnum() else "_" for ch in ascii_name).strip("_") or "Operator"
    if not slug[0].isalpha():
        slug = f"Op_{slug}"
    return f"Desktop_{slug}"[:64]


def _default_token_label() -> str:
    """The agent label init mints a bearer for on this host.

    ``<host>_agent`` is the natural choice, but a host named ``desktop``,
    ``laptop`` or ``server`` yields ``desktop_agent``: a Desktop_/Laptop_/
    server_ name outside the fleet catalog, which ``config.is_known_agent_label``
    refuses, so every call made with that bearer would answer 401 (task #1661).
    Validate the label against the same rule the hub applies and fall back to
    the neutral, non-fleet ``local_<host>_agent`` prefix when it fails.
    """
    host = socket.gethostname().split(".")[0]
    # A hostname may carry characters a label cannot; keep the label well formed.
    slug = re.sub(r"[^A-Za-z0-9_-]+", "-", host).strip("-_")[:40] or "host"
    for candidate in (f"{slug}_agent", f"local_{slug}_agent"):
        if config.is_known_agent_label(candidate):
            return candidate
    # A closed UA_AGENT_LABELS roster refuses every invented label, so the
    # operator must extend it. Still never mint a fleet-looking name.
    return f"local_{slug}_agent"


def init_main(argv: list[str] | None = None) -> int:
    """`unified-agent init` — create UA_HOME, an empty DB, and a starter env file."""
    parser = argparse.ArgumentParser(
        prog="unified-agent init",
        description="Bootstrap a fresh unified-agent install: UA_HOME, empty DB, starter env.",
    )
    parser.add_argument(
        "--force",
        action="store_true",
        help="overwrite an existing env file (the DB is always left intact)",
    )
    parser.add_argument("--json", action="store_true", help="machine-readable summary")
    parser.add_argument(
        "--print-token",
        action="store_true",
        help="also print the generated bearer tokens to stdout",
    )
    personal = parser.add_argument_group("personalization (written to settings.toml)")
    personal.add_argument("--operator-name", help="your name as the human operator")
    personal.add_argument(
        "--operator-label",
        help=(
            "identity label of your own login (default: the saved label, else "
            "Desktop_<name>; changing --operator-name alone never renames the login, "
            "pass this flag to switch to a new login)"
        ),
    )
    personal.add_argument("--workspace", help="agent workspace directory")
    personal.add_argument("--vault", help="vault path; pass an empty string to disable")
    personal.add_argument("--interactive", action="store_true", help="prompt for the values above")
    args = parser.parse_args(sys.argv[1:] if argv is None else argv)

    home = config.data_home()
    try:
        with _init_lock(home):
            return _init_install(args, home)
    except _InitLockError as exc:
        print(
            f"unified-agent init: {exc}; settings and token stores are unchanged", file=sys.stderr
        )
        return 2


class _InitLockError(Exception):
    """Initialization could not acquire its install-wide transaction lock."""


@contextlib.contextmanager
def _init_lock(home):
    """Serialize cooperating initializers on the stable installation directory.

    A replaceable lock file cannot protect a transaction: deleting or replacing
    it gives the next initializer a different inode. Flock the UA_HOME directory
    itself instead. This is an advisory lock for initializers sharing that
    installation, not protection against renaming the entire installation.
    Closing the descriptor releases flock even when initialization raises.
    """
    fd = None
    try:
        try:
            config.ensure_private_directory(home)
            fd = os.open(home, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW | os.O_CLOEXEC)
            if not stat.S_ISDIR(os.fstat(fd).st_mode):
                raise OSError("initialization lock must be an installation directory")
            fcntl.flock(fd, fcntl.LOCK_EX)
        except OSError as exc:
            raise _InitLockError(f"cannot acquire initialization lock on {home}: {exc}") from exc
        yield
    finally:
        if fd is not None:
            os.close(fd)


def _init_install(args, home) -> int:
    """Run an initialization transaction while holding the install lock."""
    from . import settings

    try:
        personal_settings = _personalization(args, home)
    except settings.SettingsError as exc:
        print(f"unified-agent init: {exc}", file=sys.stderr)
        return 2
    settings_file = settings.settings_path()
    operator_label = personal_settings["operator"]["label"]
    workspace = config.Path(personal_settings["paths"]["workspace"]).expanduser()
    workspace.mkdir(parents=True, exist_ok=True)

    env_path = home / "service.env"
    warnings = []
    ignored = _ignored_settings_workspace(settings_file, env_path, workspace)
    if ignored is not None:
        warnings.append(
            f"settings.toml paths.workspace ({ignored}) differs from UA_WORKSPACE pinned in "
            f"service.env ({workspace}); the settings.toml value is ignored because "
            "service.env is authoritative. settings.toml now records the pinned value; "
            "pass --workspace to move the workspace"
        )
    for message in warnings:
        print(f"unified-agent init: warning: {message}", file=sys.stderr)

    db_existed = config.db_path().exists()
    post_init.register_default_hooks()
    storage.init_db()

    label = _default_token_label()
    # Two-phase commit across settings.toml and the token store: validate and
    # stage settings first (nothing changes if that fails), then provision
    # tokens, then publish the staged settings. If publication fails, restore
    # the token stores so the saved operator still has their original bearer.
    staged = None
    if settings_file is not None:
        try:
            staged = settings.stage(personal_settings, settings_file)
        except (settings.SettingsError, OSError) as exc:
            print(
                f"unified-agent init: refusing: cannot save {settings_file}: {exc}; "
                "nothing was changed (see `unified-agent settings check`)",
                file=sys.stderr,
            )
            return 2
    previous_operator_label = _previous_operator_label(env_path, settings_file)
    snapshots = []
    try:
        snapshots = _snapshot_token_stores(env_path, force=args.force)
        operator_env, _ = settings.to_env({"operator": personal_settings["operator"]})
        env_action, token, operator_token, workspace_pin = _write_tokens(
            args,
            env_path,
            label=label,
            operator_label=operator_label,
            workspace=workspace,
            operator_env=operator_env,
            previous_operator_label=previous_operator_label,
        )
    except _ProvisionError as exc:
        if staged is not None:
            staged[0].unlink(missing_ok=True)
        try:
            _restore_token_stores(snapshots)
        except OSError as restore_exc:
            print(
                f"unified-agent init: refusing: {exc}; cannot restore token stores: {restore_exc}; "
                "repair service.env and the operator token store before restarting the hub",
                file=sys.stderr,
            )
        else:
            print(
                f"unified-agent init: refusing: {exc}; settings.toml and service.env are unchanged",
                file=sys.stderr,
            )
        return 2
    except BaseException:
        if staged is not None:
            staged[0].unlink(missing_ok=True)
        raise
    if staged is not None:
        try:
            staged[0].replace(staged[1])
        except OSError as exc:
            try:
                _restore_token_stores(snapshots)
            except OSError as restore_exc:
                print(
                    f"unified-agent init: cannot publish {settings_file}: {exc}; "
                    f"cannot restore token stores: {restore_exc}; repair service.env "
                    "and the operator token store before restarting the hub",
                    file=sys.stderr,
                )
            else:
                print(
                    f"unified-agent init: cannot publish {settings_file}: {exc}; "
                    "original token stores restored; settings.toml is unchanged. "
                    "Check settings-file permissions and retry",
                    file=sys.stderr,
                )
            finally:
                staged[0].unlink(missing_ok=True)
            return 2

    # Inline UA_AGENT_TOKENS live in service.env; a path value means a token file.
    token_file = _token_file_for(parse_env_file(env_path).get("UA_AGENT_TOKENS"))
    token_home = "token file" if token_file is not None else "env file"
    summary = {
        "ua_home": str(home),
        "workspace": str(workspace),
        "db": str(config.db_path()),
        "db_created": not db_existed,
        "env_file": {"path": str(env_path), "action": env_action, "workspace_pin": workspace_pin},
        "token_label": label,
        "token_file": str(token_file) if token_file is not None else None,
        "settings_file": str(settings_file) if settings_file else None,
        "operator": {
            "name": personal_settings["operator"]["name"],
            "label": operator_label,
        },
        "warnings": warnings,
    }
    if args.json:
        out = dict(summary)
        if args.print_token and token:
            out["token"] = token
        if args.print_token and operator_token:
            out["operator_token"] = operator_token
        print(json.dumps(out, indent=2))
    else:
        print(f"unified-agent init — {home}")
        print(
            f"  DB       {config.db_path()}  ({'created' if not db_existed else 'already present'})"
        )
        print(f"  workspace {workspace}  (pinned in service.env)")
        print(f"  env file {env_path}  ({env_action})")
        print(f"  settings {settings_file}")
        print(
            f"  operator {personal_settings['operator']['name']} (login label {operator_label!r})"
        )
        if env_action == "written":
            print(
                f"  token    label {label!r}"
                + (f" = {token}" if args.print_token else f" (in {token_home})")
            )
        if operator_token:
            print(
                f"  token    label {operator_label!r} (yours)"
                + (f" = {operator_token}" if args.print_token else f" (in {token_home})")
            )
        print()
        print("Next:")
        print(f"  set -a; . {env_path}; set +a       # load the env")
        print("  unified-agent doctor                 # verify")
        print("  unified-agent                        # run the server (stdio)")
    return 0


def _ignored_settings_workspace(settings_file, env_path, workspace) -> str | None:
    """The settings.toml ``paths.workspace`` this init overrides with the pin.

    Only an installed service.env pin that this run keeps can make a differing
    settings.toml value "ignored"; an explicit ``--workspace`` that moves the
    pin rewrites both files to the new path.
    """
    from . import settings

    if settings_file is None:
        return None
    raw = (parse_env_file(env_path).get("UA_WORKSPACE") or "").strip()
    if not raw:
        return None
    try:
        if _resolve_workspace_pin(raw) != str(workspace):
            return None
        configured = (settings.load(settings_file).get("paths") or {}).get("workspace")
    except settings.SettingsError:
        return None
    if not configured or config.Path(str(configured)).expanduser() == config.Path(workspace):
        return None
    return str(configured)


def _guarded(write, *args, **kwargs) -> None:
    try:
        write(*args, **kwargs)
    except OSError as exc:
        raise _ProvisionError(f"cannot write {args[0]}: {exc}") from exc


def _token_file_for(raw: str | None):
    """The resolved token file a ``UA_AGENT_TOKENS`` value names, else ``None``.

    Mirrors ``config._parse_colon_pairs``: a value starting with ``/`` or ``~``,
    or naming an existing path, is a file; anything else is inline pairs.
    """
    raw = (raw or "").strip()
    if raw and (raw.startswith(("/", "~")) or os.path.exists(raw)):
        return config.Path(raw).expanduser().resolve()
    return None


def _snapshot_token_stores(env_path, *, force: bool = False) -> list[tuple]:
    """Capture every file this invocation may change, for publication rollback.

    ``force`` is accepted for callers that predate file-backed rotation; a
    forced init now also edits the token file, so it is snapshotted either way.
    """
    paths = [env_path]
    if env_path.exists():
        token_file = _token_file_for(parse_env_file(env_path).get("UA_AGENT_TOKENS"))
        if token_file is not None:
            paths.append(token_file)
    snapshots = []
    for path in paths:
        try:
            # A dangling symlink exists as a directory entry even though its
            # target does not. Preserve that entry for publication rollback.
            link = os.readlink(path) if path.is_symlink() else None
            if path.exists():
                snapshots.append((path, path.read_bytes(), path.stat().st_mode & 0o7777, link))
            else:
                snapshots.append((path, None, None, link))
        except OSError as exc:
            raise _ProvisionError(f"cannot read token store {path}: {exc}") from exc
    return snapshots


def _restore_token_stores(snapshots: list[tuple]) -> None:
    """Restore exact bytes and modes without touching unrelated staged files.

    Restoring a file-backed ``UA_AGENT_TOKENS`` is a live bearer change (a
    running hub re-reads that file), so the rollback runs under the credential
    fence like ``_update_token_file`` (PR #1302 review).
    """
    with credential_fence.authority_fence():
        for path, body, mode, link in reversed(snapshots):
            if link is not None and (not path.is_symlink() or os.readlink(path) != link):
                tmp = path.with_name(f".{path.name}.{secrets.token_hex(6)}.tmp")
                try:
                    tmp.symlink_to(link)
                    tmp.replace(path)
                finally:
                    tmp.unlink(missing_ok=True)
            if body is None:
                if link is None:
                    path.unlink(missing_ok=True)
                continue
            target = path.resolve() if link is not None else path
            if target.read_bytes() != body or target.stat().st_mode & 0o7777 != mode:
                _write_private(target, body, mode)


def _write_tokens(
    args,
    env_path,
    *,
    label: str,
    operator_label: str,
    workspace,
    operator_env: dict[str, str],
    previous_operator_label: str | None = None,
):
    """Create or reconcile service.env.

    Returns (action, agent token, operator token, workspace pin action). The
    workspace is always pinned uncommented in service.env (#1806, #1825).

    Raises ``_ProvisionError`` (before changing anything) when the token store
    cannot be read or written.
    """
    from . import settings

    persist_operator = settings.settings_path() is None
    external_updates = {
        key: operator_env.get(key, "")
        for key in ("UA_OPERATOR_NAME", "UA_OPERATOR_LABEL", "UA_OPERATOR_ALIASES")
        if _external_operator_value(key) is not None
        and _external_operator_value(key) != operator_env.get(key, "")
    }
    token: str | None = secrets.token_urlsafe(32)
    operator_token: str | None = secrets.token_urlsafe(32)
    env_action: str
    workspace_pin = "kept"
    if env_path.exists() and not args.force:
        env_action = "kept"
        token = None  # not regenerated; existing file owns the token
        operator_token = None
        # A changed operator label must not be left without a bearer: the old
        # operator token would then resolve as an ordinary agent and nobody
        # could approve. Add a token for the new label; keep every other one.
        env_action, operator_token = _ensure_operator_token(env_path, operator_label)
        # Existing pins outrank settings.toml on restart even without --force.
        # Reconcile only identity pins already present, preserving all bearers
        # and unrelated installation settings. Publication rollback restores
        # this file and any referenced token store if the settings write fails.
        prior = parse_env_file(env_path)
        updates = {}
        for key in ("UA_OPERATOR_NAME", "UA_OPERATOR_LABEL", "UA_OPERATOR_ALIASES"):
            if key not in prior and not persist_operator and key not in external_updates:
                continue
            try:
                installed = _installed_operator_value(prior, key, env_path)
            except settings.SettingsError as exc:
                explicit = (key == "UA_OPERATOR_NAME" and args.operator_name) or (
                    key == "UA_OPERATOR_LABEL" and args.operator_label
                )
                if not explicit:
                    raise _ProvisionError(str(exc)) from exc
                # A flag can replace an unresolved pin, but repeating a
                # resolvable value must preserve its live variable reference.
                installed = None
            desired = operator_env.get(key, "")
            if installed != desired:
                updates[key] = desired
        if updates:
            _guarded(merge_write_env_file, env_path, updates, preserve_lines=True)
            env_action = "operator identity reconciled"
        pin = _workspace_pin_update(prior, workspace)
        if pin is not None:
            _guarded(_pin_workspace_in_place, env_path, pin)
            workspace_pin = "pinned"
    elif env_path.exists() and args.force:
        # --force must merge, not clobber: task #1406 blanked GCS URIs by
        # rewriting service.env from a template and wiping live targets.
        prior = parse_env_file(env_path)
        starter = _ENV_TEMPLATE.format(
            created=datetime.date.today().isoformat(),
            label=label,
            token=token,
            operator_label=operator_label,
            operator_token=operator_token,
            workspace_block=_workspace_block(workspace),
        )
        updates: dict[str, str] = {}
        for line in starter.splitlines():
            raw = line.strip()
            if not raw or raw.startswith("#") or "=" not in raw:
                continue
            k, _, v = raw.partition("=")
            try:
                parts = shlex.split(v)
            except ValueError:
                parts = []
            updates[k.strip()] = parts[0] if len(parts) == 1 else v.strip().strip("\"'")
        # Keep the deployment settings the installation already declares; only
        # keys it lacks fall back to the template default.
        for key in _FORCE_PRESERVED_KEYS & prior.keys():
            updates.pop(key, None)
        # The template always pins the workspace. A pin that already names it
        # keeps its assignment text (a $VAR reference stays a reference).
        if _workspace_pin_update(prior, workspace) is None:
            updates.pop("UA_WORKSPACE", None)
        else:
            workspace_pin = "pinned"
        # Existing service.env operator pins outrank settings.toml. Align
        # those pins with the requested identity before rotating its bearer.
        for key in ("UA_OPERATOR_NAME", "UA_OPERATOR_LABEL", "UA_OPERATOR_ALIASES"):
            if key in prior or persist_operator or key in external_updates:
                updates[key] = operator_env.get(key, "")
        # A file-backed UA_AGENT_TOKENS keeps its path: every other agent's
        # bearer lives in that file. Rotate only this host's two labels there
        # (file first, so a failure leaves service.env untouched).
        token_file = _token_file_for(prior.get("UA_AGENT_TOKENS"))
        if token_file is not None:
            updates.pop("UA_AGENT_TOKENS", None)
            _rotate_in_token_file(
                token_file,
                {label: token, operator_label: operator_token},
                retire=(previous_operator_label or "",),
            )
        elif (prior.get("UA_AGENT_TOKENS") or "").strip():
            # Inline pairs hold every other agent's bearer too (task #1797):
            # the template's two-label value used to replace them all. A forced
            # re-init still revokes the operator label it replaces.
            updates["UA_AGENT_TOKENS"] = _rotate_inline_tokens(
                prior["UA_AGENT_TOKENS"],
                {label: token, operator_label: operator_token},
                retire=(previous_operator_label or "",),
            )
        merged = merge_env_updates(prior, updates, protected=PROTECTED_GCS_KEYS)
        for key, value in prior.items():
            merged.setdefault(key, value)
        # Every key this run does not set keeps its assignment text as written.
        # Re-rendering the parsed value would quote a shell expression such as
        # UA_TRANSPORT=$MODE into the literal "$MODE", which the server rejects.
        prior_raw = parse_env_file_raw(env_path)
        verbatim = {
            key: prior_raw[key]
            for key in merged
            if key in prior_raw and key not in updates and merged[key] == prior.get(key)
        }
        _guarded(
            write_env_file,
            env_path,
            merged,
            verbatim=verbatim,
            header=(
                "# unified-agent environment — merged by `unified-agent init --force` "
                f"on {datetime.date.today().isoformat()}.\n"
                "# Protected GCS keys are never blanked when a live value exists "
                "(task #1406).\n"
                "# UA_WORKSPACE here is authoritative; settings.toml paths.workspace is "
                "informational and cannot move it (#1806).\n"
            ),
        )
        env_action = "written"
    else:
        _guarded(
            _write_private,
            env_path,
            _ENV_TEMPLATE.format(
                created=datetime.date.today().isoformat(),
                label=label,
                token=token,
                operator_label=operator_label,
                operator_token=operator_token,
                workspace_block=_workspace_block(workspace),
            )
            + (
                "\n"
                + "\n".join(
                    f"{key}={shlex.quote(value)}"
                    for key, value in (
                        operator_env if persist_operator else external_updates
                    ).items()
                )
                + "\n"
                if persist_operator or external_updates
                else ""
            ),
            0o600,
        )
        env_action = "written"
        workspace_pin = "pinned"

    return env_action, token, operator_token, workspace_pin


class _ProvisionError(Exception):
    """The operator's bearer could not be provisioned; nothing was changed."""


def _write_private(path, text: str | bytes, mode: int) -> None:
    """Atomically replace ``path`` with ``text``; the temp file is born with ``mode``.

    Creating it with ``O_EXCL`` and the final mode (never the umask default)
    means bearer tokens are not readable by other users at any point.
    """
    import os

    tmp = path.with_name(f".{path.name}.{secrets.token_hex(6)}.tmp")
    fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_EXCL, mode)
    try:
        os.fchmod(fd, mode)
        with os.fdopen(fd, "wb") as fh:
            fd = -1
            fh.write(text.encode("utf-8") if isinstance(text, str) else text)
        os.replace(tmp, path)
    except BaseException:
        if fd != -1:
            os.close(fd)
        tmp.unlink(missing_ok=True)
        raise


def _entry_sep(body: str) -> str:
    """Separator needed before appending an entry to a token file body."""
    return "" if not body or body.endswith(("\n", ",")) else "\n"


def _update_token_file(token_file, transform) -> None:
    """Rewrite ``token_file`` owner-only with ``transform(old_body)``.

    The write goes through any symlink (every reader of the target sees it)
    and raises ``_ProvisionError`` without changing the file when it cannot be
    read or written.
    """
    try:
        # config.agent_tokens() re-reads this file, so a rewrite is a live
        # bearer change: fence it against policy publication (PR #1302 review).
        with credential_fence.authority_fence():
            body = token_file.read_text()
            if token_file.stat().st_mode & 0o077:
                # Never hand new bearers to every local user.
                print(
                    f"unified-agent init: {token_file} allowed access by other users; "
                    "removing their access",
                    file=sys.stderr,
                )
            _write_private(token_file, transform(body), 0o600)
    except OSError as exc:
        raise _ProvisionError(f"cannot update token file {token_file}: {exc}") from exc


def _rotate_in_token_file(
    token_file, new_tokens: dict[str, str], retire: tuple[str, ...] = ()
) -> None:
    """Replace (by label, case-insensitively) or append ``label:token`` entries.

    Labels in ``retire`` (this install's replaced operator) are dropped. Every
    other entry, comment and line break in the file is preserved; a repeated
    stale entry for a rotated label is dropped.
    """
    wanted = {label.casefold(): (label, tok) for label, tok in new_tokens.items()}
    retired = {label.casefold() for label in retire if label} - wanted.keys()

    def transform(body: str) -> str:
        seen: set[str] = set()
        lines = []
        for line in body.splitlines():
            if line.lstrip().startswith("#"):
                lines.append(line)
                continue
            entries = []
            for entry in line.split(","):
                key = entry.partition(":")[0].strip().casefold() if ":" in entry else None
                if key in retired:
                    continue
                if key not in wanted:
                    entries.append(entry)
                elif key not in seen:
                    seen.add(key)
                    entries.append("{}:{}".format(*wanted[key]))
            lines.append(",".join(entries))
        lines += ["{}:{}".format(*pair) for key, pair in wanted.items() if key not in seen]
        return "\n".join(lines) + "\n"

    _update_token_file(token_file, transform)


def _previous_operator_label(env_path, settings_file) -> str | None:
    """The operator label this install ran under before this init, if known.

    A service.env pin outranks settings.toml, as at runtime; a ``$VAR`` pin is
    resolved the way the runtime resolves it. A pin that cannot be resolved,
    and any other unknown or unreadable value, returns None: nothing extra is
    retired rather than guessing from settings.toml.
    """
    from . import settings

    prior = parse_env_file(env_path) if env_path.exists() else {}
    if prior.get("UA_OPERATOR_LABEL"):
        try:
            label = _installed_operator_value(prior, "UA_OPERATOR_LABEL", env_path)
        except settings.SettingsError:
            return None
        return label or None
    if settings_file is None or not settings_file.exists():
        return None
    try:
        label = (settings.load(settings_file).get("operator") or {}).get("label")
    except (settings.SettingsError, OSError):
        return None
    return label if isinstance(label, str) and label else None


def _rotate_inline_tokens(
    raw: str, new_tokens: dict[str, str], retire: tuple[str, ...] = ()
) -> str:
    """Inline-pair twin of :func:`_rotate_in_token_file` (task #1797).

    Replaces (by label, case-insensitively) or appends ``label:token`` entries
    in a comma-separated ``UA_AGENT_TOKENS`` value. Labels in ``retire`` (this
    install's replaced operator) are dropped. Every other entry is kept as
    written, in order; a repeated stale entry for a rotated label is dropped.
    """
    wanted = {label.casefold(): (label, tok) for label, tok in new_tokens.items()}
    retired = {label.casefold() for label in retire if label} - wanted.keys()
    seen: set[str] = set()
    entries: list[str] = []
    for entry in raw.split(","):
        entry = entry.strip()
        if not entry:
            continue
        key = entry.partition(":")[0].strip().casefold() if ":" in entry else None
        if key in retired:
            continue
        if key not in wanted:
            entries.append(entry)
        elif key not in seen:
            seen.add(key)
            entries.append("{}:{}".format(*wanted[key]))
    entries += ["{}:{}".format(*pair) for key, pair in wanted.items() if key not in seen]
    return ",".join(entries)


def _ensure_operator_token(env_path, operator_label: str) -> tuple[str, str | None]:
    """Make sure ``operator_label`` has a bearer, keeping every existing one.

    A changed operator label must not be left without a bearer: the old
    operator token would then resolve as an ordinary agent and nobody could
    approve. ``UA_AGENT_TOKENS`` may be inline pairs or a path to a token file
    (``config._parse_colon_pairs``). A file is updated in place (through any
    symlink, so every reader of the target sees the new bearer) and the path
    in service.env is left alone. Raises ``_ProvisionError`` without changing
    anything when the token store cannot be read or written. Returns the
    env-file action and the new token, if one was minted.
    """
    raw = (parse_env_file(env_path).get("UA_AGENT_TOKENS") or "").strip()
    try:
        pairs = config._parse_colon_pairs("UA_AGENT_TOKENS", raw)
    except ValueError as exc:
        raise _ProvisionError(f"cannot add an operator token: {exc}") from exc
    if operator_label.casefold() in {label.casefold() for label, _ in pairs}:
        from . import settings

        previous = settings.load(settings.settings_path()).get("operator") or {}
        try:
            prior_label = (
                _installed_operator_value(parse_env_file(env_path), "UA_OPERATOR_LABEL", env_path)
                or _external_operator_value("UA_OPERATOR_LABEL")
                or previous.get("label")
                or config.DEFAULT_OPERATOR_LABEL
            )
        except settings.SettingsError as exc:
            raise _ProvisionError(str(exc)) from exc
        if operator_label.casefold() != prior_label.casefold():
            raise _ProvisionError(
                "cannot reuse an existing worker bearer as the operator; "
                "choose a separate operator label"
            )
        return "kept", None

    token = secrets.token_urlsafe(32)
    entry = f"{operator_label}:{token}"
    token_file = _token_file_for(raw)
    if token_file is not None:
        _update_token_file(token_file, lambda body: f"{body}{_entry_sep(body)}{entry}\n")
        return f"operator token added to {token_file}", token

    try:
        merge_write_env_file(
            env_path,
            {"UA_AGENT_TOKENS": ",".join([*(f"{lb}:{tk}" for lb, tk in pairs), entry])},
            preserve_lines=True,
            header=(
                "# unified-agent environment — operator token added by "
                f"`unified-agent init` on {datetime.date.today().isoformat()}.\n"
            ),
        )
    except OSError as exc:
        raise _ProvisionError(f"cannot update {env_path}: {exc}") from exc
    return "operator token added", token


def _format_doctor_text(report: dict) -> str:
    rows = report["checks"]
    width = max((len(c["capability"]) for c in rows), default=10)
    order = {"MISCONFIGURED": 0, "DEGRADED": 1, "UNKNOWN": 2, "DORMANT": 3, "LIVE": 4}
    out = []
    for c in sorted(rows, key=lambda c: (order.get(c["status"], 9), c["capability"])):
        out.append(f"  {c['status']:13} {c['capability']:<{width}}  {c['detail']}")
        if c.get("gate"):
            out.append(f"  {'':13} {'':<{width}}  gate: {c['gate']}")
    s = report["summary"]
    out.append(
        f"\nsummary: {s['live']} live · {s['dormant']} dormant · {s.get('degraded', 0)} degraded · "
        f"{s['misconfigured']} misconfigured · {s['unknown']} unknown"
    )
    return "\n".join(out)


def _whoami_payload(bearer: str) -> dict:
    """Verify a bearer token locally (OAuth store or static UA_AGENT_TOKENS)."""
    from . import oauth, profiles

    provider = oauth.get_provider()
    if provider is not None:
        payload = provider.whoami(bearer)
        if payload is not None:
            return payload
    label = config.agent_tokens().get(bearer)
    if label:
        return {
            "agent": label,
            "profile": profiles.default_for_identity(label),
            "scopes": [],
            "token_age_s": None,
            "expires_in": None,
            "via": "bearer",
            "client_id": None,
        }
    raise SystemExit("token did not verify (unknown bearer)")


def _format_whoami(payload: dict) -> str:
    age = payload.get("token_age_s")
    age_s = "n/a" if age is None else f"{age}s"
    exp = payload.get("expires_in")
    exp_s = "n/a" if exp is None else f"{exp}s"
    scopes = payload.get("scopes") or []
    scope_s = " ".join(scopes) if scopes else "(none)"
    return (
        f"agent={payload.get('agent')}\n"
        f"profile={payload.get('profile')}\n"
        f"scopes={scope_s}\n"
        f"token_age={age_s}\n"
        f"expires_in={exp_s}\n"
        f"via={payload.get('via')}"
    )


def doctor_main(argv: list[str] | None = None) -> int:
    """`unified-agent doctor` — run system_doctor; exit 1 on misconfig or degradation."""
    parser = argparse.ArgumentParser(
        prog="unified-agent doctor",
        description="Report LIVE/DORMANT/DEGRADED/MISCONFIGURED for every capability.",
    )
    parser.add_argument("--json", action="store_true", help="machine-readable report")
    parser.add_argument(
        "--strict",
        action="store_true",
        help="also exit non-zero if any capability is DORMANT or UNKNOWN (whole surface must be live)",
    )
    parser.add_argument(
        "--allow-unbuilt-ui",
        action="store_true",
        help=(
            "installer use: do not fail on web_ui when the install has no UI build and no "
            "UA_WEB_DIST_DIR override (it is still reported); every other failure still fails"
        ),
    )
    parser.add_argument(
        "--whoami",
        action="store_true",
        help="verify a bearer token (agent/profile/scopes/age); see --bearer",
    )
    parser.add_argument(
        "--bearer",
        default=None,
        help="token for --whoami (default: env UA_WHOAMI_BEARER, else UA_CURSOR_HUB_TOKEN)",
    )
    args = parser.parse_args(sys.argv[1:] if argv is None else argv)

    if args.whoami:
        import os

        bearer = (
            args.bearer
            or os.environ.get("UA_WHOAMI_BEARER", "").strip()
            or os.environ.get("UA_CURSOR_HUB_TOKEN", "").strip()
        )
        if not bearer:
            print(
                "doctor --whoami needs --bearer or UA_WHOAMI_BEARER / UA_CURSOR_HUB_TOKEN",
                file=sys.stderr,
            )
            return 2
        try:
            payload = _whoami_payload(bearer)
        except SystemExit as exc:
            print(str(exc), file=sys.stderr)
            return 1
        if args.json:
            print(json.dumps(payload, indent=2))
        else:
            print(_format_whoami(payload))
        return 0

    report = system_doctor()
    if args.json:
        print(json.dumps(report, indent=2))
    else:
        print(_format_doctor_text(report))

    fail = _STRICT_FAIL_STATUSES if args.strict else _FAIL_STATUSES
    checks = report["checks"]
    if args.allow_unbuilt_ui:
        checks = [
            c
            for c in checks
            if not (c.get("capability") == "web_ui" and c.get("reason") == UI_NOT_BUILT)
        ]
    return 1 if any(c["status"] in fail for c in checks) else 0


