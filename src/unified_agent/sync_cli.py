def build_managed_block(rules_md: str) -> str:
    """Wrap generated content in the ua-sync marker pair."""
    return f"{UA_SYNC_BEGIN}\n{rules_md.rstrip()}\n{UA_SYNC_END}"


def sync_opted_out(text: str | None) -> bool:
    """True when an instruction file carries the ``UA_SYNC_OFF`` marker."""
    return text is not None and UA_SYNC_OFF in text


def merge_managed_block(existing: str | None, block: str) -> str:
    """Insert or refresh the managed ua-sync block without touching other content.

    Target files are never replaced wholesale: content outside the marker pair is
    preserved byte-for-byte. A file that has no markers yet gets the block appended.
    """
    if existing is None:
        return block + "\n"
    if UA_SYNC_BEGIN in existing and UA_SYNC_END in existing:
        pattern = re.compile(re.escape(UA_SYNC_BEGIN) + r".*?" + re.escape(UA_SYNC_END), re.DOTALL)
        return pattern.sub(lambda _m: block, existing, count=1)
    return existing.rstrip("\n") + "\n\n" + block + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Sync active agent workspace with designated role, tasks, and memory."
    )
    parser.add_argument(
        "--path",
        "-p",
        type=str,
        default=".",
        help="Path to the workspace repository root (default: current directory)",
    )
    parser.add_argument(
        "--client",
        "-c",
        type=str,
        choices=sorted(_CLIENT_LABELS),
        help="Target client agent (defaults to auto-detected process tree/env)",
    )
    parser.add_argument(
        "--role",
        "-r",
        type=str,
        help="Manually override the designated agent role (e.g. Laptop_agent3)",
    )
    parser.add_argument(
        "--project",
        "-j",
        type=str,
        help="Manually override the project name (defaults to folder/git name)",
    )
    parser.add_argument(
        "--verbose", "-v", action="store_true", help="Print verbose logging/status info"
    )
    parser.add_argument(
        "--dry-run",
        "-d",
        action="store_true",
        help="Dry run: print generated instructions without writing any files or logging to vault",
    )
    parser.add_argument(
        "--include-snapshots",
        action="store_true",
        help=(
            "Embed frozen Active Tasks and Recent Project Decisions lists in the "
            "ua-sync block. Off by default: those snapshots go stale immediately "
            "and contradict Startup Grounding (task #564)."
        ),
    )

    args = parser.parse_args()

    project_path = Path(args.path).resolve()
    if not project_path.exists():
        print(f"Error: Path {project_path} does not exist.", file=sys.stderr)
        sys.exit(1)

    # 1. Determine location, client, and role
    location = detect_location()
    client = args.client or detect_client()

    if not client and not args.role:
        print(
            "Error: Could not auto-detect client agent; rerun with --role or --client.",
            file=sys.stderr,
        )
        sys.exit(2)

    # An explicit role is sufficient for isolated/satellite workflows.
    if client is None:
        client = "unknown"

    client_label = _CLIENT_LABELS.get(client, "explicit role")

    role = args.role or build_agent_role(location, client)
    project_name = args.project or detect_project(project_path)
    cockpit_workspace = is_cockpit_workspace(project_path, project_name)
    if cockpit_workspace:
        # Since 2026-09-27 the cockpit's AGENTS.md is the hand-maintained single
        # entry point (CLAUDE.md/GEMINI.md import it). A generated block would
        # reintroduce the duplicated identity map it replaced.
        print(
            f"Cockpit workspace {project_path}: AGENTS.md is hand-maintained; "
            "sync writes nothing here."
        )
        sys.exit(0)

    # Opted-out files are hand-maintained and never written. When every target
    # opts out there is nothing to do, so skip the DB and the journal too. A
    # dry run writes nothing either way, so it still prints the block.
    targets = (project_path / "CLAUDE.md", project_path / "AGENTS.md")
    opted_out = {
        t
        for t in targets
        if t.exists() and sync_opted_out(t.read_text(encoding="utf-8", errors="replace"))
    }
    if len(opted_out) == len(targets) and not args.dry_run:
        print(
            f"{project_path}: CLAUDE.md and AGENTS.md carry {UA_SYNC_OFF}; "
            "they are hand-maintained, so sync writes nothing here."
        )
        sys.exit(0)

    if args.verbose:
        print(f"Detected location: {location}")
        print(f"Detected client:   {client} (label: {client_label})")
        print(f"Target role:       {role}")
        print(f"Project name:      {project_name}")
        print(f"Target path:       {project_path}")

    # 2. Retrieve tasks and memories from the DB only when snapshots are on.
    # Default sync writes topology + Startup Grounding and must not die if the
    # memory DB is missing (task #564).
    tasks: list[dict] = []
    memories: list[dict] = []
    if args.include_snapshots:
        try:
            post_init.register_default_hooks()
            storage.init_db()
            conn = storage.connect()
            try:
                tasks = get_project_tasks(conn, project_name, role)
                memories = get_project_memories(conn, project_name)
            finally:
                conn.close()
        except Exception as e:
            print(f"Error: Could not connect to memory database: {e}", file=sys.stderr)
            sys.exit(1)

    # 3. Format the markdown output
    rules_md = generate_rules_markdown(
        role=role,
        location=location,
        client_name=client_label,
        project_name=project_name,
        tasks=tasks,
        memories=memories,
        cockpit_workspace=cockpit_workspace,
        include_snapshots=args.include_snapshots,
    )
    block = build_managed_block(rules_md)

    if args.dry_run:
        print("=== DRY RUN: Generated Markdown Rules ===")
        print(block)
        sys.exit(0)

    # 4. Write files: only the ua-sync marker block is managed; everything else in
    # CLAUDE.md / AGENTS.md is preserved. AGENTS.md lives at the project root
    # (where Codex reads it) — NOT under .agents/, which is Antigravity's own
    # separate, hand-maintained rules file and is never a sync target.
    written: list[str] = []
    try:
        for target in targets:
            if target in opted_out:
                if args.verbose:
                    print(f"Skipped {target}: carries {UA_SYNC_OFF}")
                continue
            existing = target.read_text(encoding="utf-8") if target.exists() else None
            _write_atomic(target, merge_managed_block(existing, block))
            written.append(target.name)
            if args.verbose:
                if existing is None:
                    action = "Created"
                elif UA_SYNC_BEGIN in existing:
                    action = "Refreshed managed block in"
                else:
                    action = "Appended managed block to"
                print(f"{action} {target}")
    except Exception as e:
        print(f"Error writing rule files: {e}", file=sys.stderr)
        sys.exit(1)

    # 5. Log to the journal, naming only the files actually written: an
    # opted-out file is hand-maintained and must not read as refreshed.
    written_note = "/".join(written)
    skipped_note = (
        f" Skipped {'/'.join(t.name for t in targets if t in opted_out)} (opted out)."
        if opted_out
        else ""
    )
    try:
        # Safely log using the custom agent role
        if cockpit_workspace:
            snapshot_note = (
                f"with {len(tasks)} active tasks and {len(memories)} memory references"
                if args.include_snapshots
                else "without task/memory snapshots"
            )
            journal_entry = (
                f"Synchronized role-neutral cockpit context in project '{project_name}'. "
                f"Refreshed the ua-sync block in {written_note} {snapshot_note}.{skipped_note}"
            )
        else:
            snapshot_note = (
                f"with {len(tasks)} active tasks and {len(memories)} memory references"
                if args.include_snapshots
                else "without task/memory snapshots"
            )
            journal_entry = (
                f"Synchronized client agent role to {role} in project '{project_name}'. "
                f"Refreshed the ua-sync block in {written_note} {snapshot_note}.{skipped_note}"
            )
        overflow = len(journal_entry) - _JOURNAL_ENTRY_MAX_CHARS
        if overflow > 0:
            # vault_journal refuses longer entries; a long project name must
            # not cost the sync its journal record (Devin on PR #929). Shorten
            # the name first so the skipped-file note survives, then hard-cap.
            keep = max(8, len(project_name) - overflow - 1)
            if keep < len(project_name):
                journal_entry = journal_entry.replace(
                    f"'{project_name}'", f"'{project_name[:keep]}…'", 1
                )
            if len(journal_entry) > _JOURNAL_ENTRY_MAX_CHARS:
                journal_entry = journal_entry[: _JOURNAL_ENTRY_MAX_CHARS - 1] + "…"
        vault_journal(
            entry=journal_entry,
            agent=role,
            tags=["sync", "setup", "identity"],
        )
        if args.verbose:
            print("Successfully logged sync to vault journal.")
    except Exception as e:
        # Don't fail the sync command if the vault isn't initialized or writes are blocked
        print(f"Warning: Could not write sync entry to vault journal: {e}", file=sys.stderr)
    if cockpit_workspace:
        print(
            f"Sync complete: role-neutral cockpit context refreshed for project '{project_name}'."
        )
    else:
        print(f"Sync complete: Active agent role is {role} in project '{project_name}'.")


if __name__ == "__main__":
    main()
